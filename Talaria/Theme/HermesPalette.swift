// indigo accent that turns lavender where it fills (selected chips, the model in use). Hand
// written, unlike the T3 families in Palettes.generated.swift.

private func hex(_ rgba: UInt32) -> Color {
  Color(
    .sRGB,
    red: Double((rgba >> 24) & 0xff) / 255,
    green: Double((rgba >> 16) & 0xff) / 255,
    blue: Double((rgba >> 8) & 0xff) / 255,
    opacity: Double(rgba & 0xff) / 255
  )
}


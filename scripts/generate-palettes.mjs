#!/usr/bin/env node
// Ports T3 Code's mobile color tokens (MIT, see THIRD_PARTY_NOTICES.md) into Swift.
//
//   node scripts/generate-palettes.mjs <t3code>/apps/mobile/generated-uniwind-themes.css
//
// Each `@variant <name>` block becomes one `Palette` value. Tokens that are not
// plain hex/rgba (the oklch "adaptive" ramps) and the auth-provider tokens are
// skipped; the app defines the few status tints it needs on top.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const src = process.argv[2];
if (!src) {
  console.error("usage: generate-palettes.mjs <generated-uniwind-themes.css>");
  process.exit(2);
}
const out = resolve(dirname(fileURLToPath(import.meta.url)), "../Talaria/Theme/Palettes.generated.swift");
const css = readFileSync(src, "utf8");

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const hex2 = (n) => Math.round(Math.max(0, Math.min(255, n))).toString(16).padStart(2, "0");

function toRGBA(value) {
  const v = value.trim();
  let m = v.match(/^#([0-9a-f]{3,8})$/i);
  if (m) {
    let h = m[1].toLowerCase();
    if (h.length === 3) h = [...h].map((c) => c + c).join("");
    if (h.length === 6) h += "ff";
    return h.length === 8 ? h : null;
  }
  m = v.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)(?:\s*[,/]\s*([\d.]+%?))?\s*\)$/i);
  if (m) {
    let a = 1;
    if (m[4] !== undefined) a = m[4].endsWith("%") ? parseFloat(m[4]) / 100 : parseFloat(m[4]);
    return hex2(+m[1]) + hex2(+m[2]) + hex2(+m[3]) + hex2(a * 255);
  }
  return null;
}

const variants = new Map();
let current = null;
for (const line of css.split("\n")) {
  const open = line.match(/@variant\s+([a-z0-9-]+)\s*\{/);
  if (open) { current = new Map(); variants.set(open[1], current); continue; }
  if (!current) continue;
  if (/^\s*\}/.test(line)) { current = null; continue; }
  const decl = line.match(/^\s*--color-([a-z0-9-]+):\s*(.+);\s*$/);
  if (!decl) continue;
  const [, name, value] = decl;
  if (name.startsWith("adaptive-") || name.startsWith("clerk-")) continue;
  const rgba = toRGBA(value);
  if (rgba) current.set(camel(name), rgba);
}

const names = [...variants.keys()];
if (!names.length) throw new Error("no @variant blocks found");
// Only tokens every variant defines become Palette fields.
const tokens = [...variants.get(names[0]).keys()].filter((t) => names.every((n) => variants.get(n).has(t)));

const swiftName = (variant) => camel(variant === "light" || variant === "dark" ? `standard-${variant}` : variant);

let s = `// Generated by scripts/generate-palettes.mjs from T3 Code's mobile theme tokens.
// Do not edit by hand; rerun the script instead.
//
// Color values: Copyright (c) 2026 T3 Tools Inc., MIT License (see THIRD_PARTY_NOTICES.md).

import SwiftUI

struct Palette: Sendable {
${tokens.map((t) => `  let ${t}: Color`).join("\n")}
}

private func c(_ rgba: UInt32) -> Color {
  Color(
    .sRGB,
    red: Double((rgba >> 24) & 0xff) / 255,
    green: Double((rgba >> 16) & 0xff) / 255,
    blue: Double((rgba >> 8) & 0xff) / 255,
    opacity: Double(rgba & 0xff) / 255
  )
}

extension Palette {
`;
for (const n of names) {
  const v = variants.get(n);
  s += `  static let ${swiftName(n)} = Palette(\n`;
  s += tokens.map((t) => `    ${t}: c(0x${v.get(t)})`).join(",\n");
  s += `\n  )\n\n`;
}
s = s.trimEnd() + "\n}\n";
writeFileSync(out, s);
console.log(`wrote ${out}: ${names.length} palettes x ${tokens.length} tokens (${names.map(swiftName).join(", ")})`);
